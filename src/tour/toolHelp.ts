/** A tool that was replaced keeps rendering old work, so it can still appear on
 *  a photograph edited long ago — and must still say what it is. */
function retired(successor: string, params: Record<string, string>): ToolHelp {
  return {
    what: `כלי ישן שהוחלף ב"${successor}".`,
    when: 'מופיע רק כשתמונה שנערכה מזמן עדיין משתמשת בו. אפשר להשאיר, או להחזיר לאפס ולעבור לכלי החדש.',
    params,
  };
}

