/* WHAT EVERY TOOL AND EVERY CONTROL IS FOR, in the photographer's words.
 *
 * Kept apart from the catalogue (toolRegistry.ts) on purpose: the catalogue is
 * what the engine runs, this is what the photographer reads, and the two are
 * written by different hands for different readers.
 *
 * tests/toolHelp.test.ts fails when a tool or a control in the catalogue has
 * no line here. That is the whole guarantee: a new tool cannot reach a
 * photographer without its explanation, and a renamed control cannot lose its
 * own. */

export interface ToolHelp {
  /** What it does to the photograph. */
  what: string;
  /** When a photographer reaches for it. */
  when: string;
  /** One line per control, by param id. */
  params: Record<string, string>;
}

